import { test, expect } from '@playwright/test';
test('Chrome: cycle starter decks on the play page and read their contents', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('region', { name: 'Jinx - Origins deck contents' })).toBeVisible();
  await expect(page.getByText('Deck 1 of 13 · use ← → to browse')).toBeVisible();
  await page.getByRole('button', { name: 'Next starter deck' }).click();
  await expect(page.getByRole('region', { name: 'Viktor - Origins deck contents' })).toBeVisible();
  await page.getByRole('button', { name: 'Previous starter deck' }).click();
  await page.getByRole('button', { name: 'Previous starter deck' }).click();
  const zed = page.getByRole('region', { name: 'Zed - Vendetta deck contents' });
  await expect(zed).toBeVisible();
  await expect(zed.locator('.deck-key-list span', { hasText: 'Shadow Temple' })).toBeVisible();
  await expect(zed.locator('.deck-name', { hasText: 'Kinkou Lifeblade' })).toBeVisible();
  await page.keyboard.press('ArrowLeft');
  await expect(page.getByRole('region', { name: 'Shen - Vendetta deck contents' })).toBeVisible();
  await expect(page.getByRole('combobox').first()).toHaveValue('vendetta-shen');
  await page.locator('.deck-row', { hasText: 'Disciple of Shen' }).hover();
  const enlarged = page.locator('.card-hover-preview');
  await expect(enlarged).toBeVisible();
  expect((await enlarged.boundingBox())!.width).toBeGreaterThanOrEqual(340);
  await page.screenshot({ path: '.runtime/browser-test/card-hover.png' });
  await page.mouse.move(5, 5);
  await expect(enlarged).toHaveCount(0);
  await page.waitForTimeout(500);
  await page.screenshot({ path: '.runtime/browser-test/deck-browser.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '.runtime/browser-test/deck-browser-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
