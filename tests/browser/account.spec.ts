import { test, expect } from '@playwright/test';
test('account email, six-character signup, collection recovery and owned deck filters', async ({ page }) => {
  const username = `collector${Date.now()}`, email = `${username}@example.com`;
  await page.goto('/');
  await page.getByRole('button', { name: 'Account', exact: true }).click();
  await page.getByLabel('Username', { exact: true }).fill(username);
  await page.getByLabel('Email address', { exact: true }).fill(email);
  await page.getByLabel('Password (at least 6 characters)').fill('abcdef');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page.getByRole('heading', { name: `${username}'s account` })).toBeVisible();
  await expect(page.getByLabel('Email address', { exact: true })).toHaveValue(email);
  await page.getByLabel('Email address', { exact: true }).fill(`updated${email}`);
  await page.getByRole('button', { name: 'Save email address' }).click();
  await expect(page.getByText('Email address saved.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'My cards', exact: true }).click();
  await page.getByLabel('Search collection').fill('OGN-030');
  await page.getByRole('button', { name: 'Own more OGN-030', exact: true }).click();
  await expect(page.getByLabel('Owned copies OGN-030', { exact: true })).toHaveValue('1');
  await page.getByLabel('Owned copies OGN-030', { exact: true }).fill('3');
  await page.getByLabel('Search collection').click();
  await expect(page.getByText('3 cards owned · 1 unique cards', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: 'My cards', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Your owned cards', exact: true })).toBeVisible();
  await page.getByLabel('Only owned cards', { exact: true }).check();
  await expect(page.locator('.owned-card')).toHaveCount(1);
  await expect(page.getByLabel('Owned copies OGN-030', { exact: true })).toHaveValue('3');
  await page.screenshot({ path: '.runtime/browser-test/collection.png', fullPage: true });
  await page.getByRole('button', { name: 'My decks', exact: true }).click();
  await page.getByRole('button', { name: 'Edit Jinx - Origins', exact: true }).click();
  await page.getByLabel('Only owned cards', { exact: true }).check();
  await expect(page.locator('.builder-card')).toHaveCount(1);
  await expect(page.locator('.builder-card')).toContainText('3 owned');
  await page.getByRole('button', { name: 'Account', exact: true }).click();
  await expect(page.getByLabel('Email address', { exact: true })).toHaveValue(`updated${email}`);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '.runtime/browser-test/account-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await page.getByLabel('Username', { exact: true }).fill(username);
  await page.getByLabel('Password (at least 6 characters)').fill('abcdef');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: `${username}'s account` })).toBeVisible();
});
