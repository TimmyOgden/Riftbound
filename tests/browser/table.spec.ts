import { settleMatch } from './match-helpers.ts';
import { test, expect } from '@playwright/test';
test('Chrome: visual table, champion play, moves, account and deck gallery', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'Enter the Rift' })).toBeEnabled();
  await page.getByRole('combobox').first().selectOption('proving-grounds-lux');
  await page.screenshot({ path: '.runtime/browser-test/lounge.png', fullPage: true });
  await page.getByRole('button', { name: 'Enter the Rift' }).click();
  await expect(page.locator('.game-surface')).toBeVisible();
  await expect(page.locator('.field-zone')).toHaveCount(2);
  await expect(page.locator('.hidden-hand img')).toHaveCount(0);
  await page.getByRole('button', { name: 'End turn', exact: true }).click();
  await settleMatch(page);
  await expect(page.getByRole('button', { name: 'End turn', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: /Select chosen champion/ }).click();
  await page.getByRole('button', { name: /Play card/ }).click();
  await expect(page.locator('.your-base .table-unit')).toHaveCount(1);
  await page.getByRole('button', { name: 'End turn', exact: true }).click();
  await settleMatch(page);
  await expect(page.getByRole('button', { name: 'End turn', exact: true })).toBeEnabled();
  await page.locator('.your-base .table-unit').click();
  await page.getByRole('button', { name: 'Exhaust: add 2 spell energy' }).click();
  await expect(page.locator('.spell-energy')).toContainText('2 spell energy');
  await page.getByRole('button', { name: 'End turn', exact: true }).click();
  await settleMatch(page);
  await expect(page.getByRole('button', { name: 'End turn', exact: true })).toBeEnabled();
  await expect(page.locator('.spell-energy')).toHaveCount(0);
  await page.locator('.your-base .table-unit').click();
  await expect(page.getByRole('button', { name: /Move here/ }).first()).toBeVisible();
  await page.getByRole('button', { name: /Move here/ }).first().click();
  await expect(page.locator('.your-base .table-unit')).toHaveCount(0);
  await page.screenshot({ path: '.runtime/browser-test/table.png', fullPage: true });
  await page.getByRole('button', { name: 'My decks', exact: true }).click();
  await page.getByLabel('Username', { exact: true }).fill(`visual${Date.now()}`);
  await page.getByLabel('Email address').fill(`visual${Date.now()}@example.com`);
  await page.getByLabel('Password (at least 6 characters)').fill('abcdef');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page.locator('.saved-deck-card')).toHaveCount(7);
  await expect(page.locator('.saved-deck-card .card-art')).toHaveCount(7);
  await page.screenshot({ path: '.runtime/browser-test/deck-library.png', fullPage: true });
  await page.getByRole('button', { name: 'Edit Jinx - Origins', exact: true }).click();
  await expect(page.getByLabel('Saved decks').locator('option')).toHaveCount(8);
  await expect(page.locator('.builder-thumbnail').first()).toBeVisible();
  await page.getByRole('button', { name: 'Make a copy', exact: true }).click();
  await page.getByRole('button', { name: 'Save deck', exact: true }).click();
  await expect(page.getByText('Deck saved to your account.', { exact: true })).toBeVisible();
  await expect(page.getByLabel('Saved decks').locator('option')).toHaveCount(9);
  await page.screenshot({ path: '.runtime/browser-test/decks.png', fullPage: true });
  await page.getByRole('button', { name: 'Back to my decks' }).click();
  await expect(page.locator('.saved-deck-card')).toHaveCount(8);
  await page.getByLabel('Search your decks').fill('Jinx - Origins copy');
  await expect(page.locator('.saved-deck-card')).toHaveCount(1);
  await page.getByRole('button', { name: 'Use Jinx - Origins copy', exact: true }).click();
  await expect(page.locator('.deck-selected-badge')).toContainText('Selected for play');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '.runtime/browser-test/deck-library-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Build from Lux - Proving Grounds', exact: true }).click();
  await expect(page.getByLabel('Deck name', { exact: true })).toHaveValue('Lux - Proving Grounds');
  await page.getByLabel('Deck name', { exact: true }).fill('My Lux idea');
  await page.getByRole('button', { name: 'Account', exact: true }).click();
  await page.getByRole('button', { name: 'My decks', exact: true }).click();
  await page.getByRole('button', { name: 'Resume editing', exact: true }).click();
  await expect(page.getByLabel('Deck name', { exact: true })).toHaveValue('My Lux idea');
  await page.getByRole('button', { name: 'Back to my decks' }).click();
  await page.getByRole('button', { name: 'Manage owned cards', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Your owned cards', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Play', exact: true }).click();
  await page.getByRole('button', { name: /Deck selection/ }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '.runtime/browser-test/mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});

test('Chrome: Accelerate, targeted Lee Sin buff and Viktor token activation', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'Enter the Rift' })).toBeEnabled();
  await page.getByRole('combobox').first().selectOption('origins-lee-sin');
  await page.getByRole('combobox').nth(1).selectOption('origins-viktor');
  await page.getByRole('button', { name: 'Enter the Rift' }).click();
  for (let i = 0; i < 3; i++) {
    await page.getByRole('button', { name: 'End turn', exact: true }).click();
    await settleMatch(page);
    await expect(page.getByRole('button', { name: 'End turn', exact: true })).toBeEnabled();
  }
  await page.getByRole('button', { name: /Select chosen champion/ }).click();
  await page.getByRole('button', { name: 'Accelerate · +1 energy / power' }).click();
  await expect(page.locator('.your-base .table-unit')).toHaveCount(1);
  await expect(page.locator('.your-base .unit-status')).toContainText('Ready');
  await expect(page.locator('.effect-play')).toBeAttached();
  await page.getByRole('button', { name: 'Buff a unit · 1 energy' }).click();
  await expect(page.locator('.your-base .targetable')).toHaveCount(1);
  await page.locator('.your-base .targetable').click();
  await settleMatch(page);
  await expect(page.locator('.your-base .table-unit')).toHaveClass(/buffed/);
  await expect(page.getByRole('button', { name: 'Buff a unit · 1 energy' })).toBeDisabled();
  await page.screenshot({ path: '.runtime/browser-test/abilities.png', fullPage: true });
  await page.locator('.your-base .table-unit').click();
  await page.getByRole('button', { name: /Move here/ }).first().click();
  await expect(page.locator('.combat-flash')).toHaveCount(1);
  await settleMatch(page);
  await expect(page.locator('.damage-popup').first()).toBeAttached();
  await page.screenshot({ path: '.runtime/browser-test/combat.png', fullPage: true });
  await page.getByRole('button', { name: /Deck selection/ }).click();
  await page.getByRole('combobox').first().selectOption('origins-viktor');
  await page.getByRole('button', { name: 'Enter the Rift' }).click();
  await page.getByRole('button', { name: 'Create Recruit · 1 energy' }).click();
  await settleMatch(page);
  await expect(page.locator('.your-base .table-unit')).toHaveCount(1);
  await expect(page.locator('.your-base .unit-status')).toContainText('Exhausted');
  await expect(page.getByRole('button', { name: 'Create Recruit · 1 energy' })).toBeDisabled();
  await page.getByRole('button', { name: 'End turn', exact: true }).click();
  await settleMatch(page);
  await expect(page.getByRole('button', { name: 'Create Recruit · 1 energy' })).toBeEnabled();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await expect(page.locator('.card-flights')).toBeHidden();
});
