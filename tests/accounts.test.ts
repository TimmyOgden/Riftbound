import { expect, it } from 'vitest';
import { mkdtemp, readFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { Accounts } from '../apps/server/src/accounts.ts';
import { starterDeck } from '../packages/game-content/src/index.ts';
import { riftboundStarters } from '../packages/riftbound-content/src/index.ts';
it('persists accounts and decks, rejects invalid decks, and isolates account ownership', async () => {
  const file = path.join(await mkdtemp(path.join(os.tmpdir(), 'ember-accounts-')), 'accounts.sqlite');
  let accounts = await Accounts.open(file);
  const alice = await accounts.command({ type: 'register', username: 'Alice', password: 'test-password-alice' });
  const bob = await accounts.command({ type: 'register', username: 'Bob', password: 'test-password-bob' });
  expect(alice.ok).toBe(true);
  expect(alice.decks!.map(d => d.deck)).toEqual(riftboundStarters.map(s => s.deck));
  expect((await accounts.command({ type: 'login', username: 'Alice', password: 'wrong-password' })).ok).toBe(false);
  expect((await accounts.command({ type: 'save', token: alice.token, deck: { name: 'Invalid', cards: [] } })).ok).toBe(false);
  const saved = await accounts.command({ type: 'save', token: alice.token, deck: starterDeck });
  const id = saved.decks!.at(-1)!.id;
  expect(saved.decks!.at(-1)!.deck).toEqual(starterDeck);
  expect((await accounts.command({ type: 'list', token: bob.token })).decks).toHaveLength(7);
  expect((await accounts.command({ type: 'save', token: bob.token, id, deck: starterDeck })).ok).toBe(false);
  await accounts.command({ type: 'delete', token: bob.token, id });
  expect((await accounts.command({ type: 'list', token: alice.token })).decks).toHaveLength(8);
  expect((await readFile(file)).includes(Buffer.from('test-password-alice'))).toBe(false);
  accounts = await Accounts.open(file);
  const login = await accounts.command({ type: 'login', username: 'ALICE', password: 'test-password-alice' });
  expect(login.ok).toBe(true); expect(login.decks!).toHaveLength(8); expect(login.decks!.at(-1)!.deck).toEqual(starterDeck);
  await accounts.command({ type: 'delete', token: login.token, id: login.decks![0].id });
  const again = await accounts.command({ type: 'login', username: 'Alice', password: 'test-password-alice' });
  expect(again.decks!).toHaveLength(7);
  await accounts.command({ type: 'logout', token: login.token });
  expect((await accounts.command({ type: 'list', token: login.token })).ok).toBe(false);
});
